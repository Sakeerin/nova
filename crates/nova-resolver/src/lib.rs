/// Lex and parse one embedded std module. Its source ships with the compiler,
/// so any failure is a compiler bug — but it is reported against `file_id` so
/// it is debuggable rather than silently dropped. Returns `None` when parsing
/// fails outright (nothing to merge in as a module); the caller still gets
/// the diagnostics either way.
fn std_module(src: &str, file_id: FileId) -> (Option<File>, Vec<Diagnostic>) {
    let (tokens, lex_errors) = nova_lexer::lex(src, file_id);
    let mut diags: Vec<Diagnostic> = lex_errors
        .iter()
        .map(|e| Diagnostic::error("L0001", e.to_string()).with_primary_label(e.span(), "here"))
        .collect();
    let (ast, parse_errors) = nova_parser::parse(&tokens, file_id);
    diags.extend(
        parse_errors.iter().map(|e| {
            Diagnostic::error("P0001", e.to_string()).with_primary_label(e.span(), "here")
        }),
    );
    (ast, diags)
}

/// Bind one std module's public names into every *other* module's scope,
/// leaving any name a module already defines or imports untouched (a user —
/// or another std module's own — item shadows a std one). Called once per
/// entry in [`STD_MODULES`], so this also runs std-into-std (e.g. std/core's
/// `Option` into std/collections's scope), which is what lets std/collections
/// use `Option`/`Some`/`None` with no `import` of its own.
fn import_std_module(definitions: &mut Definitions, std_exports: &Exports, std_mid: usize) {
    let values: Vec<(String, Res)> = std_exports
        .values
        .iter()
        .map(|(k, v)| (k.clone(), *v))
        .collect();
    let types: Vec<(String, DefId)> = std_exports
        .types
        .iter()
        .map(|(k, v)| (k.clone(), *v))
        .collect();
    let traits: Vec<(String, DefId)> = std_exports
        .traits
        .iter()
        .map(|(k, v)| (k.clone(), *v))
        .collect();
    for mid in 0..definitions.modules.len() {
        if mid == std_mid {
            continue;
        }
        let scope = &mut definitions.modules[mid];
        for (n, r) in &values {
            scope.values.entry(n.clone()).or_insert(*r);
        }
        for (n, id) in &types {
            scope.types.entry(n.clone()).or_insert(*id);
        }
        for (n, id) in &traits {
            scope.traits.entry(n.clone()).or_insert(*id);
        }
    }
}

/// Collect one item's definitions into `scope` (and `exp` if `pub`), pushing
/// global `Def`s into `defs`.
///
/// Also validates the item's `attrs` (Task 2): an unknown attribute name is
/// always `E0082`, `@test` on anything other than a function is `E0083`, a
/// `@test` function that is `async` or has parameters, generics, or a
/// non-`Unit` return is `E0084`, and an unknown `@test(...)` argument is
/// `E0085` — never silently ignored, so a mistyped `@tset` cannot compile into
/// a function that looks like a test and never runs as one. A well-formed
/// `@test` function is pushed onto `tests`.
///
/// Every `Item` variant carries `attrs` and is validated here, `import`,
/// `module` and `extern` included (fix round 1: `@tset` before an `extern`
/// block used to compile with zero diagnostics, since neither the AST nor
/// the parser gave those three item kinds anywhere to put a parsed
/// attribute — see `nova-ast`'s `Import`/`Module`/`ExternBlock` and
/// `nova-parser`'s `try_parse_item`). The rule is now uniform: every item may
/// carry attributes, and validation — not the AST shape — decides what is
/// legal, so there is no item kind left where a silent drop is possible.
#[allow(clippy::too_many_arguments)]
fn collect_item(
    defs: &mut Vec<Def>,
    scope: &mut ModuleScope,
    exp: &mut Exports,
    first_value: &mut IndexMap<String, Span>,
    first_type: &mut IndexMap<String, Span>,
    diagnostics: &mut Vec<Diagnostic>,
    tests: &mut Vec<TestFn>,
    item_index: usize,
    item: &Item,
) {
    match item {
        Item::Function(f) => {
            let name = f.name.value.clone();
            let span = f.name.span;
            let id = push_def(
                defs,
                Def {
                    name: name.clone(),
                    span,
                    kind: DefKind::Fn { item_index },
                },
            );
            insert_value(
                scope,
                exp,
                first_value,
                diagnostics,
                name,
                span,
                Res::Def(id),
                is_pub(f.vis),
            );
            validate_test_function(f, id, diagnostics, tests);
        }
        Item::Type(t) => {
            validate_attrs_reject_test(&t.attrs, "a type declaration", diagnostics);
            match &t.def {
                TypeDef::Sum(variants) => {
                    let name = t.name.value.clone();
                    let span = t.name.span;
                    if reject_reserved_type_name(diagnostics, &name, span) {
                        return;
                    }
                    let pubv = is_pub(t.vis);
                    let variant_defs: Vec<VariantDef> = variants
                        .iter()
                        .map(|v| VariantDef {
                            name: v.name.value.clone(),
                            span: v.name.span,
                            arity: v.fields.len(),
                        })
                        .collect();
                    let id = push_def(
                        defs,
                        Def {
                            name: name.clone(),
                            span,
                            kind: DefKind::Sum {
                                item_index,
                                variants: variant_defs,
                            },
                        },
                    );
                    insert_type(scope, exp, first_type, diagnostics, name, span, id, pubv);
                    // Variants live in the value namespace and inherit the type's
                    // visibility, so `Some(x)` / `Circle(1.0)` resolve unprefixed.
                    for (vi, v) in variants.iter().enumerate() {
                        insert_value(
                            scope,
                            exp,
                            first_value,
                            diagnostics,
                            v.name.value.clone(),
                            v.name.span,
                            Res::Variant(id, vi),
                            pubv,
                        );
                    }
                }
                TypeDef::Alias(_) => {
                    diagnostics.push(unsupported(
                        t.name.span,
                        "type aliases are not supported yet in the Phase 1 compiler",
                    ));
                }
            }
        }
        Item::Const(c) => {
            validate_attrs_reject_test(&c.attrs, "a const", diagnostics);
            let name = c.name.value.clone();
            let span = c.name.span;
            let id = push_def(
                defs,
                Def {
                    name: name.clone(),
                    span,
                    kind: DefKind::Const { item_index },
                },
            );
            insert_value(
                scope,
                exp,
                first_value,
                diagnostics,
                name,
                span,
                Res::Def(id),
                is_pub(c.vis),
            );
        }
        Item::Record(r) => {
            validate_attrs_reject_test(&r.attrs, "a record", diagnostics);
            let name = r.name.value.clone();
            let span = r.name.span;
            if reject_reserved_type_name(diagnostics, &name, span) {
                return;
            }
            let id = push_def(
                defs,
                Def {
                    name: name.clone(),
                    span,
                    kind: DefKind::Record { item_index },
                },
            );
            insert_type(
                scope,
                exp,
                first_type,
                diagnostics,
                name,
                span,
                id,
                is_pub(r.vis),
            );
        }
        Item::Trait(t) => {
            validate_attrs_reject_test(&t.attrs, "a trait", diagnostics);
            let name = t.name.value.clone();
            let span = t.name.span;
            let pubv = is_pub(t.vis);
            let id = push_def(
                defs,
                Def {
                    name: name.clone(),
                    span,
                    kind: DefKind::Trait { item_index },
                },
            );
            if scope.traits.contains_key(&name) {
                diagnostics.push(
                    Diagnostic::error("E0002", format!("duplicate trait `{name}`"))
                        .with_primary_label(span, "redefined here"),
                );
            } else {
                scope.traits.insert(name.clone(), id);
                if pubv {
                    exp.traits.insert(name, id);
                }
            }
            // Default-method bodies become their own method defs (global);
            // each associated type gets its own `DefId` too, named after
            // itself. A `match` (not `if let`) on purpose: unlike a
            // non-exhaustive `if let`, this is not something `cargo check`
            // can force open when a new `TraitItem` variant is added, so it
            // must already cover every arm.
            for (method_index, ti) in t.items.iter().enumerate() {
                match ti {
                    nova_ast::item::TraitItem::Provided(f) => {
                        push_def(
                            defs,
                            Def {
                                name: format!("{}::{}$default", t.name.value, f.name.value),
                                span: f.name.span,
                                kind: DefKind::Method {
                                    item_index,
                                    method_index,
                                    owner: MethodOwner::TraitDefault,
                                },
                            },
                        );
                    }
                    nova_ast::item::TraitItem::AssocType { name: at_name, .. } => {
                        // Not inserted into `scope.types`: an associated type
                        // is not a type name you can write bare, only
                        // reachable through a projection (`Self::Item`).
                        push_def(
                            defs,
                            Def {
                                name: at_name.value.clone(),
                                span: at_name.span,
                                kind: DefKind::AssocType { trait_def: id },
                            },
                        );
                    }
                    nova_ast::item::TraitItem::Required(_) => {}
                }
            }
        }
        Item::Impl(i) => {
            validate_attrs_reject_test(&i.attrs, "an impl block", diagnostics);
            // Impls are globally coherent — collected program-wide, resolved by
            // type rather than by name, so they are not bound into any scope.
            let self_name = type_full_name(&i.ty.value);
            for (method_index, f) in i.functions.iter().enumerate() {
                let mangled = match &i.trait_ {
                    Some(tr) => format!("{}.{}.{}", self_name, path_tail(&tr.value), f.name.value),
                    None => format!("{}.{}", self_name, f.name.value),
                };
                push_def(
                    defs,
                    Def {
                        name: mangled,
                        span: f.name.span,
                        kind: DefKind::Method {
                            item_index,
                            method_index,
                            owner: MethodOwner::Impl,
                        },
                    },
                );
            }
        }
        Item::Extern(block) => {
            validate_attrs_reject_test(&block.attrs, "an extern block", diagnostics);
            // Each declaration binds as a callable value under its (unmangled)
            // C symbol name. ABI / signature validity is checked in typeck.
            // Extern fns are module-private (the grammar has no `pub` on them).
            for (fn_index, ext_item) in block.items.iter().enumerate() {
                let ExternItem::Fn(sig) = ext_item;
                let name = sig.name.value.clone();
                let span = sig.name.span;
                let id = push_def(
                    defs,
                    Def {
                        name: name.clone(),
                        span,
                        kind: DefKind::ExternFn {
                            item_index,
                            fn_index,
                        },
                    },
                );
                insert_value(
                    scope,
                    exp,
                    first_value,
                    diagnostics,
                    name,
                    span,
                    Res::Def(id),
                    false,
                );
            }
        }
        Item::Import(imp) => {
            validate_attrs_reject_test(&imp.attrs, "an import", diagnostics);
            // Otherwise handled in pass 2.
        }
        Item::Module(m) => {
            validate_attrs_reject_test(&m.attrs, "a module declaration", diagnostics);
            // Carries no items of its own to collect.
        }
    }
}

/// `E0089`: `name` is one of [`RESERVED_TYPE_NAMES`]. Called from the sum-type
/// and record arms of [`collect_item`] — the two forms that introduce a type
/// name — before either pushes a `Def` or inserts into the type namespace, so
/// a rejected declaration registers nothing: it does not occupy a `DefId`, is
/// not collected by any later pass, and cannot collide with a genuine
/// duplicate of the same name. Two declarations under the same reserved name
/// each raise their own `E0089` rather than the second colliding as `E0002`
/// — for the same reason: neither one is ever registered, so there is
/// nothing on record for a second occurrence to collide with.
///
/// "Not collected by any later pass" holds only because every such pass in
/// `nova-typeck` walks `Definitions::defs()` rather than the AST directly, so
/// skipping `push_def` here is sufficient — today. That is a cross-crate
/// invariant this function's ordering relies on but cannot enforce; nothing
/// stops a future pass from walking items directly instead. The same drift
/// class this module already flags for `convert_ty`'s and `qualifier_self_ty`'s
/// tables (see [`RESERVED_TYPE_NAMES`]'s own doc): a comment, not a compiler
/// backstop.
fn reject_reserved_type_name(diagnostics: &mut Vec<Diagnostic>, name: &str, span: Span) -> bool {
    if !RESERVED_TYPE_NAMES.contains(&name) {
        return false;
    }
    diagnostics.push(
        Diagnostic::error(
            "E0089",
            format!(
                "`{name}` is already a built-in type; a type declared under \
                 this name could never be referred to in a type annotation, \
                 since `{name}` in a type position never resolves to a \
                 declaration under this name"
            ),
        )
        .with_primary_label(span, "redeclares a built-in type name"),
    );
    true
}

/// Attribute names the compiler recognizes. An attribute whose name is not in
/// this list is always `E0082` — parsing an attribute and then enforcing
/// nothing about its name is exactly the failure mode `@test` must not be
/// allowed: a misspelled `@tset` that compiled would define a function that
/// looks like a test and never runs as one.
const KNOWN_ATTRIBUTES: &[&str] = &["test"];

/// Arguments `@test(...)` accepts. Anything else is `E0085`.
const KNOWN_TEST_ARGS: &[&str] = &["should_panic"];

/// The `E0084` note attached when a `@test` function is `async`
/// (see [`test_shape_violations`]).
///
/// A note rather than a longer message because it has to be *actionable on its
/// own*: the whole point of rejecting the shape is that the user's next edit
/// should be the working one, so the replacement pattern is spelled out as
/// source rather than described, and `block_on`'s role in it is named.
const TEST_ASYNC_NOTE: &str = "an `async fn` returns a future, and a `@test` function's result is \
     discarded rather than awaited, so an `async` test's body would never run; \
     write the test as a synchronous one that drives the future itself, e.g. \
     `@test fn t() { assert_eq(block_on(f()), 42) }` — `block_on` runs `f()`'s \
     future to completion and produces its value";

/// `E0082`: `attr`'s name is not in [`KNOWN_ATTRIBUTES`]. Shared by every
/// item kind that can carry attributes, so a typo is caught the same way no
/// matter what it is attached to.
///
/// Labels `attr.name.span`, never `attr.span`: `attr.span` (see
/// `nova-parser`'s `parse_attributes`) is set to the span of the leading `@`
/// token alone — one byte wide, never covering the name that follows it — so
/// underlining it would point at the `@` and leave the actual misspelled
/// word unmarked. `attr.name` is a separate `Spanned<String>` built by
/// `parse_ident`, with its own accurate span over just the identifier text,
/// and is what every diagnostic in this file uses instead. `attr.span` is
/// read nowhere in this module.
fn unknown_attribute(attr: &Attribute) -> Diagnostic {
    Diagnostic::error(
        "E0082",
        format!(
            "unknown attribute `@{}`; known attributes are: {}",
            attr.name.value,
            KNOWN_ATTRIBUTES.join(", "),
        ),
    )
    .with_primary_label(attr.name.span, "unknown attribute")
}

/// Validate the attributes of an item that can never itself be a test: every
/// item kind except a function (record, type declaration, trait, impl block,
/// const, import, module, extern block — see [`validate_test_function`] for
/// the function case). An unknown name is still `E0082`; `@test` on one of
/// these is `E0083`, since only a function can ever run as a test. `kind`
/// names the item for the message and already carries its article (e.g.
/// `"a record"`, `"an impl block"`).
fn validate_attrs_reject_test(attrs: &[Attribute], kind: &str, diagnostics: &mut Vec<Diagnostic>) {
    for attr in attrs {
        if attr.name.value == "test" {
            diagnostics.push(
                Diagnostic::error(
                    "E0083",
                    format!("`@test` can only be applied to a function, not {kind}"),
                )
                .with_primary_label(attr.name.span, "not a function"),
            );
        } else if !KNOWN_ATTRIBUTES.contains(&attr.name.value.as_str()) {
            diagnostics.push(unknown_attribute(attr));
        }
    }
}

/// Validate a function's attributes and, if it carries a well-formed `@test`,
/// push a [`TestFn`] onto `tests`. `def_id` is the caller's already-collected
/// `DefId` for `f` (from its own `push_def`), so a rejected `@test` still
/// leaves the function itself resolved and callable like any other —
/// rejection refuses only its *test-ness*, never its existence in the
/// namespace.
///
/// Pushes onto `tests` in the order [`resolve_program`]'s item walk visits
/// this function, which is source order — see [`TestFn`]'s doc comment for
/// why that must hold exactly and
/// `collected_tests_are_in_source_order_with_should_panic_attached` in
/// `nova-typeck` for the test that pins it.
///
/// Pushes **at most one** `TestFn`, even if `f` carries more than one
/// well-formed `@test` (syntactically legal — `f.attrs` is a plain `Vec`
/// with no uniqueness constraint on `name`, the same reason `@derive(...)`
/// and `@test` can coexist on one function). Without the `collected` guard
/// below, `@test\n@test\nfn t() {}` would push the same `def_id`/name onto
/// `tests` twice, and `nova test` would list and run one function as if it
/// were two different tests. The first well-formed `@test`, in attribute
/// order, is the one whose `should_panic` wins; later ones are still
/// validated (an invalid argument or bad shape on a second `@test` still
/// reports its own diagnostic) but never collected again.
fn validate_test_function(
    f: &Function,
    def_id: DefId,
    diagnostics: &mut Vec<Diagnostic>,
    tests: &mut Vec<TestFn>,
) {
    let mut collected = false;
    for attr in &f.attrs {
        if attr.name.value != "test" {
            diagnostics.push(unknown_attribute(attr));
            continue;
        }
        let mut well_formed = true;
        let mut should_panic = false;
        for arg in &attr.args {
            if arg.value == "should_panic" {
                should_panic = true;
            } else {
                diagnostics.push(
                    Diagnostic::error(
                        "E0085",
                        format!(
                            "unknown `@test` argument `{}`; the accepted arguments are: {}",
                            arg.value,
                            KNOWN_TEST_ARGS.join(", "),
                        ),
                    )
                    .with_primary_label(arg.span, "unknown argument"),
                );
                well_formed = false;
            }
        }
        let violations = test_shape_violations(f);
        if !violations.is_empty() {
            let names: Vec<&str> = violations.iter().map(|(name, _)| *name).collect();
            let mut diag = Diagnostic::error(
                "E0084",
                format!("a `@test` function may not have {}", names.join(", ")),
            )
            .with_primary_label(f.name.span, "invalid test signature");
            for (name, span) in &violations {
                if let Some(span) = span {
                    diag = diag.with_secondary_label(*span, format!("{name} here"));
                }
            }
            if f.is_async {
                diag = diag.with_note(TEST_ASYNC_NOTE);
            }
            diagnostics.push(diag);
            well_formed = false;
        }
        if well_formed && !collected {
            tests.push(TestFn {
                def_id,
                name: f.name.value.clone(),
                should_panic,
            });
            collected = true;
        }
    }
}

/// Ways a function's signature disqualifies it from `@test` (`E0084`): an
/// `async` body, parameters, generics, or an explicit non-`Unit` return type. A
/// test is called with no arguments and its result is discarded, so there is no
/// caller that could ever supply the one or consume the other. A missing
/// return type and an explicit `-> ()` are both `Unit` and neither is a
/// violation — only an explicit *non*-`Unit` return type is.
///
/// `async` is rejected for the same reason and one more: an `async fn` returns
/// a future, and a discarded future is never awaited, so the body of an
/// `async` `@test` could not run at all. Rejecting it is what the `nova test`
/// design specified from the start (`@test fn t() { block_on(f()) }` is the
/// supported way to test async code); accepting it silently is what
/// `TEST_ASYNC_NOTE` exists to steer a user out of.
///
/// The `async` violation carries no span because the AST records `is_async` as
/// a bare `bool` with no span of its own, and the `async` keyword precedes the
/// name, so `f.name.span` would point a label at the wrong token. `None` is
/// therefore "no better span than the primary label's", not "no location".
fn test_shape_violations(f: &Function) -> Vec<(&'static str, Option<Span>)> {
    let mut violations = Vec::new();
    if f.is_async {
        violations.push(("an `async` body", None));
    }
    if let (Some(first), Some(last)) = (f.params.first(), f.params.last()) {
        violations.push(("parameters", Some(first.name.span.merge(last.ty.span))));
    }
    if let (Some(first), Some(last)) = (f.generics.first(), f.generics.last()) {
        violations.push((
            "generic parameters",
            Some(first.name.span.merge(last.name.span)),
        ));
    }
    if let Some(rt) = &f.return_ty {
        if !matches!(&rt.value, Type::Tuple(items) if items.is_empty()) {
            violations.push(("a non-Unit return type", Some(rt.span)));
        }
    }
    violations
}

/// Bind another module's public names into the importing module's scope.
fn resolve_import(
    definitions: &mut Definitions,
    exports: &[Exports],
    by_name: &FxHashMap<&str, usize>,
    mid: usize,
    imp: &Import,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let span = imp.path.span;
    // Only single-segment module imports are supported. A qualified or nested
    // path (`a::b`) would otherwise silently drop its leading segments and bind
    // an unrelated module; reject it explicitly like `import ... as`.
    if imp.path.value.segments.len() > 1 {
        diagnostics.push(unsupported(
            span,
            "qualified or nested import paths (`a::b`) are not supported yet; \
             import a top-level module by its name",
        ));
        return;
    }
    let target_name = imp
        .path
        .value
        .segments
        .last()
        .map(|s| s.value.as_str())
        .unwrap_or("");
    let Some(&target) = by_name.get(target_name) else {
        diagnostics.push(
            Diagnostic::error("E0001", format!("cannot find module `{target_name}`"))
                .with_primary_label(span, "no such module"),
        );
        return;
    };
    if target == mid {
        diagnostics.push(
            Diagnostic::error("E0001", format!("module `{target_name}` imports itself"))
                .with_primary_label(span, "self-import"),
        );
        return;
    }
    match &imp.kind {
        ImportKind::Simple => {
            // Glob: bring all of the target module's public names into scope.
            let names: Vec<(String, Res)> = exports[target]
                .values
                .iter()
                .map(|(k, v)| (k.clone(), *v))
                .collect();
            for (n, r) in names {
                bind_value(&mut definitions.modules[mid], diagnostics, n, span, r);
            }
            let tys: Vec<(String, DefId)> = exports[target]
                .types
                .iter()
                .map(|(k, v)| (k.clone(), *v))
                .collect();
            for (n, id) in tys {
                bind_type(&mut definitions.modules[mid], diagnostics, n, span, id);
            }
            let trs: Vec<(String, DefId)> = exports[target]
                .traits
                .iter()
                .map(|(k, v)| (k.clone(), *v))
                .collect();
            for (n, id) in trs {
                bind_trait(&mut definitions.modules[mid], diagnostics, n, span, id);
            }
        }
        ImportKind::List(names) => {
            for n in names {
                let name = &n.value;
                let mut found = false;
                if let Some(r) = exports[target].values.get(name).copied() {
                    bind_value(
                        &mut definitions.modules[mid],
                        diagnostics,
                        name.clone(),
                        n.span,
                        r,
                    );
                    found = true;
                }
                if let Some(id) = exports[target].types.get(name).copied() {
                    bind_type(
                        &mut definitions.modules[mid],
                        diagnostics,
                        name.clone(),
                        n.span,
                        id,
                    );
                    found = true;
                }
                if let Some(id) = exports[target].traits.get(name).copied() {
                    bind_trait(
                        &mut definitions.modules[mid],
                        diagnostics,
                        name.clone(),
                        n.span,
                        id,
                    );
                    found = true;
                }
                if !found {
                    diagnostics.push(
                        Diagnostic::error(
                            "E0001",
                            format!("`{name}` is not a public item of module `{target_name}`"),
                        )
                        .with_primary_label(n.span, "not found or not `pub`"),
                    );
                }
            }
        }
        ImportKind::Alias(_) => {
            diagnostics.push(unsupported(
                span,
                "`import ... as` aliases are not supported yet",
            ));
        }
    }
}

fn is_pub(vis: nova_ast::item::Visibility) -> bool {
    matches!(vis, nova_ast::item::Visibility::Pub)
}

#[allow(clippy::too_many_arguments)]
fn insert_value(
    scope: &mut ModuleScope,
    exp: &mut Exports,
    first: &mut IndexMap<String, Span>,
    diagnostics: &mut Vec<Diagnostic>,
    name: String,
    span: Span,
    res: Res,
    is_pub: bool,
) {
    if scope.values.contains_key(&name) {
        let mut diag = Diagnostic::error("E0002", format!("duplicate definition of `{name}`"))
            .with_primary_label(span, "redefined here");
        if let Some(prev) = first.get(&name) {
            diag = diag.with_secondary_label(*prev, "first defined here");
        } else {
            diag = diag.with_note(format!("`{name}` is a compiler builtin"));
        }
        diagnostics.push(diag);
        return;
    }
    first.insert(name.clone(), span);
    if is_pub {
        exp.values.insert(name.clone(), res);
    }
    scope.values.insert(name, res);
}

#[allow(clippy::too_many_arguments)]
fn insert_type(
    scope: &mut ModuleScope,
    exp: &mut Exports,
    first: &mut IndexMap<String, Span>,
    diagnostics: &mut Vec<Diagnostic>,
    name: String,
    span: Span,
    id: DefId,
    is_pub: bool,
) {
    if scope.types.contains_key(&name) {
        let mut diag = Diagnostic::error("E0002", format!("duplicate definition of type `{name}`"))
            .with_primary_label(span, "redefined here");
        if let Some(prev) = first.get(&name) {
            diag = diag.with_secondary_label(*prev, "first defined here");
        }
        diagnostics.push(diag);
        return;
    }
    first.insert(name.clone(), span);
    if is_pub {
        exp.types.insert(name.clone(), id);
    }
    scope.types.insert(name, id);
}

/// Bind an imported name into a module's value namespace, or report a conflict.
fn bind_value(
    scope: &mut ModuleScope,
    diagnostics: &mut Vec<Diagnostic>,
    name: String,
    span: Span,
    res: Res,
) {
    if scope.values.contains_key(&name) {
        diagnostics.push(
            Diagnostic::error(
                "E0002",
                format!("`{name}` is already defined or imported in this module"),
            )
            .with_primary_label(span, "conflicting import"),
        );
        return;
    }
    scope.values.insert(name, res);
}

fn bind_type(
    scope: &mut ModuleScope,
    diagnostics: &mut Vec<Diagnostic>,
    name: String,
    span: Span,
    id: DefId,
) {
    if scope.types.contains_key(&name) {
        diagnostics.push(
            Diagnostic::error(
                "E0002",
                format!("type `{name}` is already defined or imported in this module"),
            )
            .with_primary_label(span, "conflicting import"),
        );
        return;
    }
    scope.types.insert(name, id);
}

fn bind_trait(
    scope: &mut ModuleScope,
    diagnostics: &mut Vec<Diagnostic>,
    name: String,
    span: Span,
    id: DefId,
) {
    if scope.traits.contains_key(&name) {
        diagnostics.push(
            Diagnostic::error(
                "E0002",
                format!("trait `{name}` is already defined or imported in this module"),
            )
            .with_primary_label(span, "conflicting import"),
        );
        return;
    }
    scope.traits.insert(name, id);
}

fn unsupported(span: Span, msg: &str) -> Diagnostic {
    Diagnostic::error("E0900", msg).with_primary_label(span, "not supported yet")
}

/// A short textual head for a type, used only to build unique method
/// symbol names (semantic resolution happens later in the type checker).
/// A textual name for an impl self type that includes its type arguments, so
/// that two impls sharing a head but differing in arguments (`Pair<Int, Bool>`
/// vs `Pair<Int, Int>`) yield distinct method names and never collide when
/// monomorphized. Uses only `_`/`.`-style separators to stay linker-safe.
/// A generic parameter contributes its source name (`Box<T>` → `Box_T`); a
/// concrete instantiation still gets a distinct mangled instance via type
/// arguments at monomorphization.
fn type_full_name(ty: &nova_ast::Type) -> String {
    match ty {
        nova_ast::Type::Path { path, args } => {
            let head = path_tail(path);
            if args.is_empty() {
                head
            } else {
                let parts: Vec<String> = args.iter().map(|a| type_full_name(&a.value)).collect();
                format!("{head}_{}", parts.join("_"))
            }
        }
        nova_ast::Type::Array(elem) => format!("Arr_{}", type_full_name(&elem.value)),
        _ => "anon".to_string(),
    }
}

/// The last segment of a path (`a::b::c` → `c`).
fn path_tail(path: &nova_ast::Path) -> String {
    path.segments
        .last()
        .map(|s| s.value.clone())
        .unwrap_or_default()
}


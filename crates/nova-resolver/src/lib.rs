/// Type names the compiler owns, which a user type declaration may not take.
///
/// `nova-typeck`'s `convert_ty` resolves each of these to its built-in type,
/// or to a shadowing generic parameter, wherever it runs — never to a
/// declaration under this name, which is what `resolve_type` would have to
/// find instead. So a type declared under one of these names could never be
/// referred to in a type annotation.
///
/// That is narrower than "every use". A record literal resolves its head
/// through `resolve_type` directly, never through `convert_ty`
/// (`check_record_literal`), and a sum type's variants live in the *value*
/// namespace, independent of the type name — so construction and pattern
/// matching for a type declared under one of these names worked before this
/// list was enforced. An `impl` header's self type is a `convert_ty` site
/// too, so an `impl` written for one of these names attaches to the
/// built-in, never to the declaration. So what worked before this list was
/// enforced was construction, pattern matching, and inferred local
/// bindings; a signature or an `impl` did not. See `CHANGELOG.md` for
/// exactly what this change breaks.
///
/// `Future` is here and is not a primitive: it is the one built-in type name
/// taking a type argument, handled separately from the nullary table.
/// `Unit` is deliberately absent — it is not a nameable type name; unit is
/// spelled `()`.
///
/// `Bytes` joined later, for the same reason as the five original
/// primitives: an ordinary nullary entry in `convert_ty`'s table, with no
/// carve-out of its own like `Future`'s or `Unit`'s above.
///
/// This is the list, and both `convert_ty`'s and `qualifier_self_ty`'s
/// built-in-name tables (`crates/nova-typeck/src/check.rs`) are expected to
/// agree with it.
pub const RESERVED_TYPE_NAMES: [&str; 7] =
    ["Int", "Float", "Bool", "Char", "String", "Future", "Bytes"];

/// What kind of definition a [`DefId`] refers to.
#[derive(Debug, Clone)]
pub enum DefKind {
    /// A function; the payload is the index of the item in `File::items`.
    Fn { item_index: usize },
    /// A sum type declaration with its variants.
    Sum {
        item_index: usize,
        variants: Vec<VariantDef>,
    },
    /// A record (struct) declaration.
    Record { item_index: usize },
    /// A constant; payload is the item index.
    Const { item_index: usize },
    /// A trait declaration.
    Trait { item_index: usize },
    /// A method: an `ast::Function` living inside an impl block, or a
    /// trait's default-method body. `method_index` selects it within the
    /// owner (impl `functions`, or the trait's provided items).
    Method {
        item_index: usize,
        method_index: usize,
        owner: MethodOwner,
    },
    /// An `extern` function declaration (a C-ABI import, no Nova body).
    /// `fn_index` selects the declaration within the extern block's `items`.
    ExternFn { item_index: usize, fn_index: usize },
    /// An associated type declared in a trait (`type Item`). Carries its
    /// owning trait so a projection can be checked against the right trait
    /// without a separate lookup table.
    AssocType { trait_def: DefId },
}

/// Where a [`DefKind::Method`] lives.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MethodOwner {
    /// A method defined in an `impl` block (`item_index` → the impl item).
    Impl,
    /// A default-method body in a `trait` declaration (`item_index` → the
    /// trait item, `method_index` → its `functions`-style provided list).
    TraitDefault,
}

/// One variant of a sum type.
#[derive(Debug, Clone)]
pub struct VariantDef {
    pub name: String,
    pub span: Span,
    /// Number of payload fields (types live in the AST, indexed by the parent).
    pub arity: usize,
}

/// A single top-level definition.
#[derive(Debug, Clone)]
pub struct Def {
    pub name: String,
    pub span: Span,
    pub kind: DefKind,
}

/// What a name in expression position resolves to.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Res {
    /// A top-level definition.
    Def(DefId),
    /// Variant `variant_index` of the sum type `DefId`.
    Variant(DefId, usize),
    /// A compiler builtin.
    Builtin(Builtin),
}

/// Index of a module within a compiled program.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct ModuleId(pub u32);

/// One module's visible namespaces: its own items (public and private), the
/// implicit std modules (see [`STD_MODULES`]), and names it imports.
/// Resolution is performed relative to a module.
#[derive(Debug, Default)]
struct ModuleScope {
    name: String,
    values: FxHashMap<String, Res>,
    types: FxHashMap<String, DefId>,
    traits: FxHashMap<String, DefId>,
}

/// The item-level namespaces of a whole program (one or more modules).
///
/// `defs` and `DefId`s are global; name lookups are **module-relative** — a
/// name is resolved in the scope of the module that owns the item currently
/// being checked (see [`Definitions::module_of`]).
#[derive(Debug, Default)]
pub struct Definitions {
    defs: Vec<Def>,
    modules: Vec<ModuleScope>,
    /// Merged-item-index → owning module.
    item_module: Vec<u32>,
}

impl Definitions {
    /// All collected definitions, indexable by `DefId.0`.
    pub fn defs(&self) -> &[Def] {
        &self.defs
    }

    /// Look up a definition by id.
    pub fn def(&self, id: DefId) -> &Def {
        &self.defs[id.0 as usize]
    }

    /// The module that owns the item at `item_index` in the merged file.
    pub fn module_of(&self, item_index: usize) -> ModuleId {
        ModuleId(self.item_module.get(item_index).copied().unwrap_or(0))
    }

    /// Number of modules in the program.
    pub fn module_count(&self) -> usize {
        self.modules.len()
    }

    /// The name of a module.
    pub fn module_name(&self, module: ModuleId) -> &str {
        self.modules
            .get(module.0 as usize)
            .map(|m| m.name.as_str())
            .unwrap_or("")
    }

    /// Resolve a name in *value* position, relative to `module`.
    pub fn resolve_value(&self, module: ModuleId, name: &str) -> Option<Res> {
        self.modules
            .get(module.0 as usize)
            .and_then(|m| m.values.get(name).copied())
    }

    /// Resolve a name in *type* position, relative to `module`.
    pub fn resolve_type(&self, module: ModuleId, name: &str) -> Option<DefId> {
        self.modules
            .get(module.0 as usize)
            .and_then(|m| m.types.get(name).copied())
    }

    /// Resolve a name in *trait* position, relative to `module`.
    pub fn resolve_trait(&self, module: ModuleId, name: &str) -> Option<DefId> {
        self.modules
            .get(module.0 as usize)
            .and_then(|m| m.traits.get(name).copied())
    }

    /// Iterate all method definitions as `(DefId, item_index, method_index,
    /// owner)`.
    pub fn methods(&self) -> impl Iterator<Item = (DefId, usize, usize, MethodOwner)> + '_ {
        self.defs
            .iter()
            .enumerate()
            .filter_map(|(i, d)| match d.kind {
                DefKind::Method {
                    item_index,
                    method_index,
                    owner,
                } => Some((DefId(i as u32), item_index, method_index, owner)),
                _ => None,
            })
    }

    /// Iterate all function definitions as `(DefId, item_index)`.
    pub fn functions(&self) -> impl Iterator<Item = (DefId, usize)> + '_ {
        self.defs
            .iter()
            .enumerate()
            .filter_map(|(i, d)| match d.kind {
                DefKind::Fn { item_index } => Some((DefId(i as u32), item_index)),
                _ => None,
            })
    }

    /// Iterate all `extern` function declarations as
    /// `(DefId, item_index, fn_index)` (fn_index into the extern block's items).
    pub fn extern_functions(&self) -> impl Iterator<Item = (DefId, usize, usize)> + '_ {
        self.defs
            .iter()
            .enumerate()
            .filter_map(|(i, d)| match d.kind {
                DefKind::ExternFn {
                    item_index,
                    fn_index,
                } => Some((DefId(i as u32), item_index, fn_index)),
                _ => None,
            })
    }
}

/// A source module: a parsed file plus its module name (file stem).
pub struct ModuleSource<'a> {
    pub name: String,
    pub file: &'a File,
}

/// The public exports of one module (its `pub` items), used to resolve imports.
#[derive(Default)]
struct Exports {
    values: FxHashMap<String, Res>,
    types: FxHashMap<String, DefId>,
    traits: FxHashMap<String, DefId>,
}

fn push_def(defs: &mut Vec<Def>, def: Def) -> DefId {
    let id = DefId(defs.len() as u32);
    defs.push(def);
    id
}

/// A well-formed `@test` function, collected by [`collect_item`] in the same
/// order [`resolve_program`]'s item walk visits it — source order (modules in
/// registration order, items within a module in file order; see
/// `collected_tests_are_in_source_order_with_should_panic_attached` in
/// `nova-typeck` for why that order must be exact and stable). Task 3 reads
/// this to build a dispatching `main` that runs one test per process,
/// selected by index; Task 5 reads test names back out of the compiled
/// binary, not from this struct directly — so an index and a name can never
/// silently disagree between the two only if this order never does either.
#[derive(Debug, Clone)]
pub struct TestFn {
    pub def_id: DefId,
    pub name: String,
    pub should_panic: bool,
}

/// Output of [`resolve`]: the namespace table, the merged file whose
/// `item_index`es the definitions refer to (the input plus the implicit std
/// modules, see [`STD_MODULES`]), and any diagnostics. Downstream stages must
/// type-check against this `file`, not the original input, since
/// `item_index`es index into it.
#[derive(Debug)]
pub struct ResolveResult {
    pub definitions: Definitions,
    pub file: File,
    pub diagnostics: Vec<Diagnostic>,
    pub tests: Vec<TestFn>,
}

/// Output of [`resolve_program`]: the merged file, its namespaces, any
/// diagnostics, and the `@test` functions collected along the way. The merged
/// file's `item_index`es are what `Definitions` refers to, so downstream
/// stages consume both together.
pub struct ProgramResolution {
    pub file: File,
    pub definitions: Definitions,
    pub diagnostics: Vec<Diagnostic>,
    pub tests: Vec<TestFn>,
}

/// Collect the item-level namespace of a single file.
///
/// Reports `E0002` for duplicate definitions in the same namespace. Imports
/// and `module` declarations are accepted but ignored in Phase 1 (single-file
/// compilation); traits/impls/records are collected in later Phase 1 steps.
pub fn resolve(file: &File) -> ResolveResult {
    let sources = [ModuleSource {
        name: "main".to_string(),
        file,
    }];
    // No `FileDb` to register the embedded std modules into here, so every
    // one of them gets the same `FileId::DUMMY` sentinel used throughout the
    // test suite — one per `STD_MODULES` entry, in order.
    let std_files: Vec<FileId> = STD_MODULES.iter().map(|_| FileId::DUMMY).collect();
    let prog = resolve_program(&sources, &std_files, None);
    ResolveResult {
        definitions: prog.definitions,
        file: prog.file,
        diagnostics: prog.diagnostics,
        tests: prog.tests,
    }
}

/// Resolve a multi-module program: collect each module's item namespace,
/// enforce `pub` visibility across modules, wire up `import`s, and merge all
/// items into one file for whole-program compilation downstream.
///
/// `std_files` are the [`FileId`]s the caller registered each of
/// [`STD_MODULES`]'s sources under, one per entry, in the same order. Only the
/// driver owns a `FileDb`, so the ids cannot be invented here; threading them
/// through means a syntax error inside an embedded std module is reported
/// against a real file instead of [`FileId::DUMMY`]. The single-module
/// [`resolve`] wrapper passes `FileId::DUMMY` for each, since it has no
/// `FileDb` to register into. Entries beyond `std_files`'s length are simply
/// not compiled in (the driver always supplies one id per `STD_MODULES`
/// entry, so this is not expected to happen).
///
/// `extra_std` is `Some((`[`STD_TEST_MODULE`]`, file_id))` under `nova test`
/// and `None` otherwise (the driver decides). When present it is treated as
/// one more std module — glob-imported into every other module exactly like
/// each [`STD_MODULES`] entry, and on the receiving end of their glob-imports too
/// (so `assert_eq`'s bounds can name `Eq`/`Debug` with no `import`) — but it
/// is threaded through this one parameter rather than folded into
/// `STD_MODULES` itself, so that array's length stays fixed regardless of
/// compilation mode; every other consumer of `STD_MODULES` (and the driver's
/// one-`FileId`-per-entry allocation) is therefore unaffected by its
/// existence.
///
/// `item_index`es in the returned [`ProgramResolution::file`] are global
/// (module items concatenated in `modules` order, plus the implicit std
/// modules last, in [`STD_MODULES`] order, plus `extra_std` if present).
pub fn resolve_program(
    modules: &[ModuleSource],
    std_files: &[FileId],
    extra_std: Option<((&str, &str), FileId)>,
) -> ProgramResolution {
    let mut definitions = Definitions::default();
    let mut diagnostics = Vec::new();
    let mut merged = Vec::new();
    let mut tests = Vec::new();

    // Every `STD_MODULES` entry plus, only when the caller passed one, the
    // extra std module — combined here so the rest of this function has one
    // uniform list to iterate instead of a special case for the extra entry.
    let std_entries: Vec<(&str, &str)> = STD_MODULES
        .iter()
        .copied()
        .chain(extra_std.map(|(entry, _)| entry))
        .collect();
    let std_file_ids: Vec<FileId> = std_files
        .iter()
        .copied()
        .chain(extra_std.map(|(_, file_id)| file_id))
        .collect();

    // Compile each implicit std module (in `std_entries` order) so their
    // public types/traits/values get real DefIds and layouts (and are then
    // glob-imported into every other module below). Each ships with the
    // compiler, so a parse failure here is a compiler bug — but it is
    // reported against a real file so it is debuggable, and a module that
    // fails to parse outright is skipped entirely (`None`) rather than
    // silently merged in as empty.
    let std_modules: Vec<Option<File>> = std_entries
        .iter()
        .zip(std_file_ids.iter())
        .map(|(&(_, src), &file_id)| {
            let (ast, diags) = std_module(src, file_id);
            diagnostics.extend(diags);
            ast
        })
        .collect();

    // They go *after* all user modules, so user module indices are
    // unaffected — module 0 stays the first user module.
    let user_count = modules.len();
    let all: Vec<ModuleSource> = modules
        .iter()
        .map(|m| ModuleSource {
            name: m.name.clone(),
            file: m.file,
        })
        .chain(
            std_entries
                .iter()
                .zip(std_modules.iter())
                .filter_map(|(&(name, _), file)| {
                    file.as_ref().map(|file| ModuleSource {
                        name: name.to_string(),
                        file,
                    })
                }),
        )
        .collect();

    // The std modules that parsed successfully are exactly the contiguous
    // range after the user modules — nothing else is appended after them —
    // so "is `mid` *a* std module" (rather than checking against one stored
    // "the std module" index) is this one range check.
    let std_start = user_count;
    let is_std_module = |mid: usize| mid >= std_start;

    let mut exports: Vec<Exports> = Vec::new();

    // A scope per module, seeded with the compiler builtins. `Builtin::GLOBAL`
    // goes into every module; `Builtin::STD_ONLY` goes only into an std
    // module's own scope, so none of them ever becomes a reserved word in
    // user code (see the `Builtin` doc comments).
    for (mid, m) in all.iter().enumerate() {
        let mut scope = ModuleScope {
            name: m.name.clone(),
            ..Default::default()
        };
        for b in Builtin::GLOBAL {
            scope.values.insert(b.name().to_string(), Res::Builtin(b));
        }
        if is_std_module(mid) {
            for b in Builtin::STD_ONLY {
                scope.values.insert(b.name().to_string(), Res::Builtin(b));
            }
        }
        definitions.modules.push(scope);
        exports.push(Exports::default());
    }

    // Pass 1: collect each module's own definitions into its scope + exports.
    for (mid, m) in all.iter().enumerate() {
        let mut first_value: IndexMap<String, Span> = IndexMap::new();
        let mut first_type: IndexMap<String, Span> = IndexMap::new();
        for item in &m.file.items {
            let item_index = merged.len();
            definitions.item_module.push(mid as u32);
            collect_item(
                &mut definitions.defs,
                &mut definitions.modules[mid],
                &mut exports[mid],
                &mut first_value,
                &mut first_type,
                &mut diagnostics,
                &mut tests,
                item_index,
                &item.value,
            );
            merged.push(item.clone());
        }
    }

    // Pass 2: resolve `import`s, binding other modules' public names.
    let by_name: FxHashMap<&str, usize> = all
        .iter()
        .enumerate()
        .map(|(i, m)| (m.name.as_str(), i))
        .collect();
    for (mid, m) in all.iter().enumerate() {
        for item in &m.file.items {
            if let Item::Import(imp) = &item.value {
                resolve_import(
                    &mut definitions,
                    &exports,
                    &by_name,
                    mid,
                    imp,
                    &mut diagnostics,
                );
            }
        }
    }

    // Glob each std module's public names into every *other* module — LAST,
    // so it is the lowest-priority binding: a name the module already defines
    // or imports wins (no conflict), and only otherwise-unbound names fall
    // through to a std module. A program may thus define or import its own
    // `Option`/`Result`/`Vec`. This also runs std-into-std — std/core's
    // exports glob into std/collections's scope exactly as they would into a
    // user module's, which is what lets std/collections use
    // `Option`/`Some`/`None` with no `import` of its own.
    for (mid, std_exports) in exports.iter().enumerate().skip(std_start) {
        import_std_module(&mut definitions, std_exports, mid);
    }

    ProgramResolution {
        file: File { items: merged },
        definitions,
        diagnostics,
        tests,
    }
}

